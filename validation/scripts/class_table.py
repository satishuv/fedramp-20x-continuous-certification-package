#!/usr/bin/env python3
"""The class comparison table in docs/certification-classes.md, rendered from
the canonical data instead of typed by hand (AUD-F55).

Sources, all generated by the build from the pinned dataset:
  profiles/class-{a,b,c}/profile.json            rules resolved per class
  profiles/class-d-future/readiness-register.json  Class D register count
  profiles/common/ksi-profile.json               indicators: mandatory at A,
                                                 optional at B, automated-method
                                                 minimums (FRC-CSX-VVK)
  references/fedramp-consolidated-rules.json     SDR-CSX-KMT force per class

Usage:
  python validation/scripts/class_table.py            print the table
  python validation/scripts/class_table.py --check    exit 1 if the doc differs
  python validation/scripts/class_table.py --write    replace the doc's table
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.abspath(os.path.join(HERE, "..", ".."))
DOC = os.path.join(BASE, "docs", "certification-classes.md")
DATASET = os.path.join(BASE, "references", "fedramp-consolidated-rules.json")
KSI_PROFILE = os.path.join(BASE, "profiles", "common", "ksi-profile.json")
CLASS_D_REGISTER = os.path.join(BASE, "profiles", "class-d-future", "readiness-register.json")
HEADER = "## What differs between classes"
OPTIONAL_MARK = "**Optional:**"


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def _find_rule(node, rid):
    if isinstance(node, dict):
        if rid in node and isinstance(node[rid], dict):
            return node[rid]
        for v in node.values():
            r = _find_rule(v, rid)
            if r is not None:
                return r
    return None


def class_facts():
    """Every number and force the table states, read from the canonical files."""
    facts = {"rules": {}, "kmt_force": {}, "vvk_min": {}}
    for cls in ("a", "b", "c"):
        prof = load(os.path.join(BASE, "profiles", f"class-{cls}", "profile.json"))
        rules = prof.get("rules") or []
        facts["rules"][cls] = len(rules) if isinstance(rules, list) else len(rules.keys())
    facts["rules"]["d"] = load(CLASS_D_REGISTER).get("count")
    kp = load(KSI_PROFILE)
    indicators = kp["indicators"]
    indicators = list(indicators.values()) if isinstance(indicators, dict) else indicators
    facts["ksi_total"] = len(indicators)
    facts["ksi_mandatory_a"] = sum(1 for i in indicators if i.get("class_a_obligation") == "mandatory")
    optional_b = sorted(i["ksi_id"] for i in indicators
                        if str(((i.get("varies_by_class") or {}).get("b") or {}).get("statement", ""))
                        .startswith(OPTIONAL_MARK))
    facts["ksi_optional_b"] = optional_b
    facts["ksi_baseline_b"] = facts["ksi_total"] - len(optional_b)
    for key, cls in (("class_a", "a"), ("class_b", "b"), ("class_c", "c"), ("class_d_future", "d")):
        values = {(i.get("minimum_automated_methods") or {}).get(key) for i in indicators}
        if len(values) != 1:
            raise SystemExit(f"FRC-CSX-VVK minimum is not uniform across indicators at {cls}: {values}")
        facts["vvk_min"][cls] = values.pop()
    kmt = _find_rule(load(DATASET), "SDR-CSX-KMT") or {}
    for cls in ("a", "b", "c", "d"):
        facts["kmt_force"][cls] = ((kmt.get("varies_by_class") or {}).get(cls) or {}).get("force")
    return facts


def render_table(facts=None):
    f = facts or class_facts()
    r, v, k = f["rules"], f["vvk_min"], f["kmt_force"]
    total, mand_a, base_b, opt_b = f["ksi_total"], f["ksi_mandatory_a"], f["ksi_baseline_b"], len(f["ksi_optional_b"])

    def methods(n):
        return "none required" if not n else f"at least {n}"

    rows = [
        "| | Class A | Class B | Class C | Class D |",
        "|---|---|---|---|---|",
        f"| Provider rules resolved | {r['a']} | {r['b']} | {r['c']} plus overlay | {r['d']} in readiness register |",
        f"| Indicators in scope | {mand_a} mandatory of {total} | {base_b} baseline plus {opt_b} optional, up to {total} | all {total} | all {total} |",
        f"| Automated methods per indicator (`FRC-CSX-VVK`) | {methods(v['a'])} | {methods(v['b'])} | {methods(v['c'])} | {methods(v['d'])} |",
        f"| Historical KSI metrics including persistent-validation status (`SDR-CSX-KMT`) | `{k['a']}` include | `{k['b']}` include 30-day and one-year summaries | `{k['c']}`: summaries plus all daily data up to the past year, where available | `{k['d']}` significantly supersede lower classes (specifics pending) |",
        "| Support in this repository | full | full | full | register only |",
    ]
    return "\n".join(rows)


def doc_table(text):
    """(start, end) line indexes of the table that follows HEADER, or None."""
    lines = text.split("\n")
    try:
        h = lines.index(HEADER)
    except ValueError:
        return None
    i = h + 1
    while i < len(lines) and not lines[i].startswith("|"):
        i += 1
    j = i
    while j < len(lines) and lines[j].startswith("|"):
        j += 1
    return (i, j) if j > i else None


README = os.path.join(BASE, "README.md")


def sync_prose(text, facts=None):
    """Rewrite the count-bearing sentences of docs/certification-classes.md that
    test_docs_class_table.py anchors, so an adoption that changes a class count
    (2026.11.02.01 moved Class A from 41 to 42) needs no hand edit. Each
    pattern replaces only the digits; the sentence shape is unchanged."""
    import re
    f = facts or class_facts()
    r = f["rules"]
    mand_a, total, base_b = f["ksi_mandatory_a"], f["ksi_total"], f["ksi_baseline_b"]
    subs = [
        (r"so the \d+ rules are the ones FedRAMP named",
         f"so the {r['a']} rules are the ones FedRAMP named"),
        (r"\d+ are mandatory at Class A and the other \d+ carry",
         f"{mand_a} are mandatory at Class A and the other {total - mand_a} carry"),
        (r"\d+ rules to \d+, and \d+ indicators to \d+",
         f"{r['a']} rules to {r['b']}, and {mand_a} indicators to {base_b}"),
        (r"holds \d+ rules resolved against the class D variants",
         f"holds {r['d']} rules resolved against the class D variants"),
    ]
    for pat, rep in subs:
        text = re.sub(pat, rep, text)
    return text


def sync_readme(text, facts=None):
    """Rewrite the 'Rules resolved' cell of the README class rows (A to D)."""
    import re
    f = facts or class_facts()
    r = f["rules"]
    cells = {"A": f"{r['a']}", "B": f"{r['b']}", "C": f"{r['c']} plus overlay", "D": f"{r['d']}"}
    for cls, cell in cells.items():
        text = re.sub(rf"^\| {cls} \| [^|]+ \|", f"| {cls} | {cell} |", text, count=1, flags=re.M)
    return text


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    facts = class_facts()
    table = render_table(facts)
    if "--check" in argv or "--write" in argv:
        with open(DOC, encoding="utf-8") as fh:
            text = fh.read()
        with open(README, encoding="utf-8") as fh:
            readme = fh.read()
        span = doc_table(text)
        if span is None:
            print(f"{os.path.relpath(DOC, BASE)}: no table found after '{HEADER}'")
            return 1
        lines = text.split("\n")
        current = "\n".join(lines[span[0]:span[1]])
        lines[span[0]:span[1]] = table.split("\n")
        new_text = sync_prose("\n".join(lines), facts)
        new_readme = sync_readme(readme, facts)
        if new_text == text and new_readme == readme:
            print("class table: docs match the canonical data (table, prose and README row)")
            return 0
        if "--write" in argv:
            if new_text != text:
                with open(DOC, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(new_text)
                print(f"class table: rewrote {os.path.relpath(DOC, BASE)} from the canonical data")
            if new_readme != readme:
                with open(README, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(new_readme)
                print("class table: rewrote the README class rows from the canonical data")
            return 0
        print("class table: docs DIFFER from the canonical data.")
        if current != table:
            print("--- doc\n" + current + "\n--- canonical\n" + table)
        else:
            print("(table matches; a prose sentence or the README class row differs)")
        print("Run: python validation/scripts/class_table.py --write")
        return 1
    print(table)
    return 0


if __name__ == "__main__":
    sys.exit(main())
